// outputShape returns the per-verb Output override when one exists, else the
// per-group default. Keyed lookup keeps renderReference deterministic.
func outputShape(verb, group string) string {
	if s, ok := outputShapeOverrides[verb]; ok {
		return s
	}
	return groupOutputDefault(group)
}

// groupOutputDefault returns the deterministic per-group output-shape note.
func groupOutputDefault(group string) string {
	switch group {
	case "navigation":
		return "terse `relpath:line:col<TAB>payload`, one locus per line, sorted and deduped (1-based); navigation verbs append a snippet line."
	case "edit":
		return "an applied-edit summary (files touched, fuzzy strategy when used); a failing edit prints a typed `kind: msg` to stderr."
	case "fileops":
		return "file content or a `relpath`-anchored listing; structured per-line output piped plain (no ANSI)."
	case "diagnostics":
		return "`relpath:line:col<TAB>severity<TAB>message` diagnostics, or the available code actions / formatted output."
	case "memory":
		return "the memory body or a ranked FTS5 search result set, one entry per line."
	case "repomap":
		return "a ranked, token-budgeted structural overview or context bundle (relpath-anchored)."
	default:
		return "terse, `relpath:line:col`-anchored output; a failing verb prints a typed `kind: msg` to stderr and exits non-zero."
	}
}

// useThisNotThat returns the per-verb "use this, not that" override when one
// exists, else the per-group default. Keyed lookup keeps render deterministic.
func useThisNotThat(verb, group string) string {
	if s, ok := useThisNotThatOverrides[verb]; ok {
		return s
	}
	return groupUseDefault(group, verb)
}

// groupUseDefault returns the deterministic per-group "use this verb, not the
// standard tool" pointer.
func groupUseDefault(group, verb string) string {
	cmd := "`helix " + verb + "`"
	switch group {
	case "navigation":
		return "Use " + cmd + " for symbol-level questions instead of `grep`/`grep -r` — it resolves real definitions and references via the LSP, not string matches."
	case "edit":
		return "Use " + cmd + " for symbol-aware edits instead of `sed`/`sed -i` — it edits by AST/symbol, tolerant of LLM output drift."
	case "fileops":
		return "Use " + cmd + " instead of `cat`/`find`/`grep -r` — terse, `relpath`-anchored output built for agents."
	case "diagnostics":
		return "Use " + cmd + " instead of parsing raw build output — it surfaces structured, locus-anchored diagnostics and quick-fixes."
	case "memory":
		return "Use " + cmd + " for durable project/session memory instead of ad-hoc scratch notes."
	case "repomap":
		return "Use " + cmd + " for a ranked structural overview instead of reading many files by hand."
	default:
		return "Use " + cmd + " instead of falling back to grep/sed/cat for this task."
	}
}
